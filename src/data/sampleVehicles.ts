// Helper to generate a realistic 16x16 / 12x16 map table
function generateMapMatrix(
  rows: number,
  cols: number,
  baseVal: number,
  rowFactor: number,
  colFactor: number,
  curvature: number = 1.0
): number[][] {
  const matrix: number[][] = [];
  for (let r = 0; r < rows; r++) {
    const row: number[] = [];
    for (let c = 0; c < cols; c++) {
      const val = Math.round(
        (baseVal + r * rowFactor + Math.pow(c, curvature) * colFactor) * 10
      ) / 10;
      row.push(val);
    }
    matrix.push(row);
  }
  return matrix;
}

